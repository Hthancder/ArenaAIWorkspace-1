for _k, _v in _PRACTICE.items():
    T.setdefault(_k, _v)

def convert(obj, missing, path=""):
    if isinstance(obj, dict):
        out = {}
        for k, v in obj.items():
            if k.endswith("_one"):
                continue  # vi has a single plural form
            key = k[:-6] if k.endswith("_other") else k
            nv = convert(v, missing, f"{path}.{k}")
            out[key] = nv
        return out
    if isinstance(obj, str):
        if obj in T:
            return T[obj]
        if obj.strip() == "" or obj in ("WAV", "MIDI", "WebGL", "2x", "OK", "Y", "2D"):
            return obj
        missing.add(obj)
        return obj
    return obj

def main():
    missing = set()
    for f in sorted(glob.glob(os.path.join(LOC, 'en', '*.json'))):
        name = os.path.basename(f)
        d = json.load(open(f, encoding='utf-8'))
        vi = convert(d, missing)
        out = os.path.join(LOC, 'vi', name)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        json.dump(vi, open(out, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
        print("wrote", out)
    if missing:
        print(f"\n{len(missing)} MISSING:")
        for m in sorted(missing):
            print(" ", repr(m))
    else:
        print("\nfull coverage")

if __name__ == '__main__':
    main()
