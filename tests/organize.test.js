assert(start>=0&&end>start);
const ctx={OrganizeTools:O,id:()=> 'new',validUrl:u=>/^https?:\/\//i.test(u)};
vm.runInNewContext(source.slice(start,end),ctx);
const restored=ctx.validateImport({format:'tabspace-backup',version:1,groups:[{name:'Work',tags:['group'],items:[{url:'https://example.com',title:'T',tags:['tab'],note:'My note'}]}]});
