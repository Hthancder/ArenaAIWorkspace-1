const assert=require('node:assert/strict');
const P=require('../extension/presets.js');
assert.equal(P.normalizeDomain('GitHub.COM'),'github.com');
assert.equal(P.normalizeDomain('bücher.de'),'xn--bcher-kva.de');
for(const bad of ['https://github.com','github.com/path','*.github.com','github.com:443','user@github.com','github.com?x']) assert.throws(()=>P.normalizeDomain(bad));
assert(P.matches('https://github.com/a',['github.com'],false));
assert(!P.matches('https://notgithub.com',['github.com'],true));
assert(!P.matches('https://sub.github.com',['github.com'],false));
assert(P.matches('https://sub.github.com',['github.com'],true));
assert(!P.matches('chrome://github.com',['github.com'],true));
assert.equal(P.reason({active:true}),'Đang xem');
assert.equal(P.reason({pinned:true}),'Đã ghim');
assert.equal(P.reason({audible:true}),'Đang phát âm thanh');
assert.equal(P.reason({incognito:true}),'Ẩn danh');
const [p]=P.validate([{name:'Work',domains:['github.com'],groupId:'old'}],()=> 'new',new Map([['old','mapped']]));assert.equal(p.groupId,'mapped');
assert.equal(P.validate([{name:'X',domains:['x.com'],groupId:'missing'}],()=> 'new',new Map())[0].groupId,null);
console.log('Preset matching, protections and import: OK');
const preset={domains:['github.com'],subdomains:true,paths:['https://docs.example.com/work'],exactUrls:['https://special.example/p?q=2#part'],excludePaths:['https://github.com/personal'],excludeDomains:['private.github.com'],excludeUrls:['https://github.com/org?q=secret']};
assert(P.matchesPreset('https://github.com/company/repo',preset));
assert(!P.matchesPreset('https://github.com/personal/repo',preset));
assert(P.matchesPreset('https://github.com/personalized',preset));
assert(!P.matchesPreset('https://private.github.com/a',preset));
assert(!P.matchesPreset('https://github.com/org?q=secret',preset));
assert(P.matchesPreset('https://docs.example.com/work/sub?x=1#foo',preset));
assert(!P.matchesPreset('https://docs.example.com/workshop',preset));
assert(!P.matchesPreset('http://docs.example.com/work',preset));
assert(!P.matchesPreset('https://docs.example.com:444/work',preset));
assert(P.matchesPreset('https://special.example/p?q=2#part',preset));
assert(!P.matchesPreset('https://special.example/p?q=2',preset));
assert.throws(()=>P.normalizeUrl('https://example.com/work?q=1',true));
assert.throws(()=>P.normalizeUrl('https://user:pass@example.com/'));
const rules=P.validate([{name:'URLs',domains:[],exactUrls:['https://x.test/?a=1','https://x.test/?a=2'],paths:['https://x.test/work'],excludePaths:['https://x.test/work/private'],groupId:'g'}],()=> 'new',new Map([['g','dest']]));
assert.equal(rules[0].exactUrls.length,2);assert.equal(rules[0].excludePaths.length,1);assert.equal(rules[0].groupId,'dest');
console.log('Preset URL rules, boundaries and exclusions: OK');
const presets=[{id:'one',name:'One',domains:['example.com'],subdomains:true},{id:'two',name:'Two',domains:['example.com'],subdomains:true,excludePaths:['https://example.com/private']},{id:'three',name:'Three',domains:['elsewhere.test']}];
assert.deepEqual(P.overlaps('https://example.com/work',presets,'one').map(x=>x.id),['two']);assert.deepEqual(P.overlaps('https://example.com/private/x',presets,'one'),[]);assert.deepEqual(P.overlaps('https://notexample.com/work',presets,'one'),[]);console.log('Preset overlap honors per-preset exclusions: OK');
