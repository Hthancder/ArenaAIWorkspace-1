// Regression: cancelling a dialog must bypass native required-field validation.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('extension/dashboard.js', 'utf8');
const start = source.indexOf('function showDialog(');
const end = source.indexOf('\nfunction keyboardHelp(', start);
assert(start >= 0 && end > start);
const cancel = {formNoValidate: false};
const heading={};const body = {innerHTML: '', querySelector: selector => selector==='h2'?heading:cancel};
const dialog = {attrs:{},setAttribute(k,v){this.attrs[k]=v},removeAttribute(k){delete this.attrs[k]},open: false, showModal(){this.open = true}, close(){this.open = false}};
const form = {};
const context = {$: s => ({'#dialogBody':body, '#dialog':dialog, '#dialogForm':form}[s]), FormData: class {}, notify: () => {}};
vm.runInNewContext(source.slice(start,end), context);
let submitted = false;
context.showDialog('<input required><button value="cancel">Hủy</button>', () => {submitted = true});
assert.equal(dialog.attrs['aria-labelledby'],'dialogTitle');assert.equal(heading.id,'dialogTitle');
assert.equal(cancel.formNoValidate, true, 'Cancel must bypass browser form validation');
assert.equal(dialog.open, true);
form.onsubmit({preventDefault(){}, submitter:{value:'cancel'}, currentTarget:form});
assert.equal(dialog.open, false, 'Cancel must close dialog');
assert.equal(submitted, false, 'Cancel must not perform action');
(async()=>{
 let locked=false, calls=0, messages=[];
 context.MutationLock={run:async work=>{assert.equal(locked,false,'dialog must acquire only one lock');locked=true;try{return await work()}finally{locked=false}}};
 context.notify=message=>messages.push(message);
 context.showDialog('<h2>Import</h2>',async()=>{assert.equal(locked,true);calls++});
 const submitter={value:'submit',disabled:false};
 await form.onsubmit({preventDefault(){},submitter,currentTarget:form});
 assert.equal(calls,1);assert.equal(locked,false);assert.equal(submitter.disabled,false);assert.deepEqual(messages,[]);
 console.log('Dialog cancel and single-lock submission: OK');
})().catch(e=>{console.error(e);process.exitCode=1});
